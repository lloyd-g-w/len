#!/usr/bin/env bash
# Regenerates every platform icon of Len from one design.
#
#   app/tool/generate_icons.sh        (from anywhere; needs Nix or resvg+magick+oxipng)
#
# Design (docs/DESIGN.md §1, §9): flat, Swiss minimal. An Ink (#000000) tile;
# the mark is the "gesture" scribble in paper white standing on one short
# ruling-blue rule (the dark-mode accent #4DA3FF, square ends): ink written on
# a notebook's ruled line. No gradients, sheens or shadows.
#
# Source of truth:
#   tool/branding/glyph.path   the scribble: Material Symbols "gesture",
#                              24×24 units (spans y 3..21). The library sidebar
#                              shows the same symbol (`Symbols.gesture_sharp`)
#                              in Ink, without a tile. Apache-2.0 (Google).
#   this script                colours and geometry of every variant.
#
# Outputs (all committed):
#   tool/branding/*.svg                         design variants (also previews)
#   web/icons/*, web/favicon.png                PWA / browser icons
#   android/app/src/main/res/{drawable,mipmap-*}/   adaptive (vector) icon,
#                                               legacy PNGs, splash icon
#   windows/runner/resources/app_icon.ico
#   linux/packaging/icons/                      hicolor PNGs + scalable SVG
#
# Not generated, keep in step by hand: the splash / window background (Board
# #F4F4F4, dark #1A1A1A) in android res/values*/colors.xml, web/manifest.json
# and web/index.html.
set -euo pipefail

if ! command -v resvg >/dev/null || ! command -v magick >/dev/null || ! command -v oxipng >/dev/null; then
  exec nix shell nixpkgs#resvg nixpkgs#imagemagick nixpkgs#oxipng -c bash "$0" "$@"
fi

APP="$(cd "$(dirname "$0")/.." && pwd)"
BR="$APP/tool/branding"
GLYPH="$(tr -d '\n' < "$BR/glyph.path")"

INK="#000000"     # tile
PAPER="#FFFFFF"   # the scribble
RULE="#4DA3FF"    # ruling blue (the dark-mode accent: it reads on Ink)

# The mark in glyph units: the scribble (x 3..21, y 3..21) and the rule just
# under its baseline, as wide as the scribble. RULE_S_* is a heavier rule with
# a wider gap for renders of 32 px and less (favicon, small .ico and hicolor
# sizes), where the thin one would merge with the scribble.
RULE_X=3; RULE_W=18
RULE_Y=21.75; RULE_H=1.75     # ≈ 1/10 of the scribble's height
RULE_S_Y=22; RULE_S_H=2.5
CX=12                         # horizontal centre of the mark

calc() { awk "BEGIN { printf \"%.2f\", $1 }"; }

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# ---- SVG variants ----------------------------------------------------------
# $1 file, $2 tile element, $3 mark scale, $4 small rule (0/1).
# The mark's box (y 3 .. bottom of the rule) is centred in the 512 canvas.
svg() {
  local file=$1 tile=$2 s=$3 small=${4:-0} ry=$RULE_Y rh=$RULE_H tx ty
  if [[ $small == 1 ]]; then ry=$RULE_S_Y; rh=$RULE_S_H; fi
  tx=$(calc "256 - $CX * $s")
  ty=$(calc "256 - (3 + $ry + $rh) / 2 * $s")
  cat > "$file" <<EOF
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <!-- Len app icon. Generated by app/tool/generate_icons.sh — edit there. -->
  $tile
  <g transform="translate($tx $ty) scale($s)">
    <path fill="$PAPER" d="$GLYPH"/>
    <rect x="$RULE_X" y="$ry" width="$RULE_W" height="$rh" fill="$RULE"/>
  </g>
</svg>
EOF
}

rounded="<rect x=\"24\" y=\"24\" width=\"464\" height=\"464\" rx=\"80\" fill=\"$INK\"/>"
square="<rect width=\"512\" height=\"512\" fill=\"$INK\"/>"
circle="<circle cx=\"256\" cy=\"256\" r=\"236\" fill=\"$INK\"/>"

svg "$BR/len.svg"          "$rounded" 12.5     # desktop, web "any", legacy launcher
svg "$BR/len-small.svg"    "$rounded" 14   1   # ≤ 32 px renders
svg "$BR/len-maskable.svg" "$square"  11       # full bleed, mark inside the 80 % safe zone
svg "$BR/len-round.svg"    "$circle"  11.5     # Android legacy round launcher
svg "$BR/len-touch.svg"    "$square"  12       # iOS home screen (iOS rounds it)

render() { resvg -w "$2" -h "$2" "$1" "$3"; }
# Picks the small variant for tiny sizes.
icon_for() { if (( $1 <= 32 )); then echo "$BR/len-small.svg"; else echo "$BR/len.svg"; fi; }

# ---- Web -------------------------------------------------------------------
WEB="$APP/web"
cp "$BR/len.svg" "$WEB/icons/len.svg"
cp "$BR/len-maskable.svg" "$WEB/icons/len-maskable.svg"
render "$BR/len.svg" 192 "$WEB/icons/Icon-192.png"
render "$BR/len.svg" 512 "$WEB/icons/Icon-512.png"
render "$BR/len-maskable.svg" 192 "$WEB/icons/Icon-maskable-192.png"
render "$BR/len-maskable.svg" 512 "$WEB/icons/Icon-maskable-512.png"
render "$BR/len-touch.svg" 180 "$WEB/icons/apple-touch-icon.png"
render "$BR/len-small.svg" 32 "$WEB/favicon.png"

# ---- Windows (.ico with the sizes Explorer / taskbar use) ------------------
ico=()
for s in 16 20 24 32 40 48 64 96 128 256; do
  render "$(icon_for $s)" $s "$TMP/ico-$s.png"
  ico+=("$TMP/ico-$s.png")
done
magick "${ico[@]}" "$APP/windows/runner/resources/app_icon.ico"

# ---- Linux (hicolor theme, installed into the bundle by linux/CMakeLists.txt) ----
LX="$APP/linux/packaging/icons"
rm -rf "$LX"
for s in 32 48 64 128 256 512; do
  mkdir -p "$LX/${s}x${s}/apps"
  render "$(icon_for $s)" $s "$LX/${s}x${s}/apps/dev.len.len.png"
done
mkdir -p "$LX/scalable/apps"
cp "$BR/len.svg" "$LX/scalable/apps/dev.len.len.svg"

# ---- Android ---------------------------------------------------------------
RES="$APP/android/app/src/main/res"
declare -A dens=([mdpi]=48 [hdpi]=72 [xhdpi]=96 [xxhdpi]=144 [xxxhdpi]=192)
for d in "${!dens[@]}"; do
  mkdir -p "$RES/mipmap-$d"
  render "$BR/len.svg" "${dens[$d]}" "$RES/mipmap-$d/ic_launcher.png"
  render "$BR/len-round.svg" "${dens[$d]}" "$RES/mipmap-$d/ic_launcher_round.png"
done

mkdir -p "$RES/mipmap-anydpi-v26" "$RES/drawable"
for name in ic_launcher ic_launcher_round; do
  cat > "$RES/mipmap-anydpi-v26/$name.xml" <<'EOF'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/tool/generate_icons.sh. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <!-- Android 13+ themed icons: the mark's alpha, tinted by the system. -->
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
EOF
done

cat > "$RES/drawable/ic_launcher_background.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/tool/generate_icons.sh. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#FF${INK#\#}" android:pathData="M0,0h108v108h-108z"/>
</vector>
EOF

# The mark as vector paths: $1 scribble colour, $2 rule colour (#AARRGGBB).
mark_paths() {
  cat <<EOF
        <path android:fillColor="$1" android:pathData="$GLYPH"/>
        <path android:fillColor="$2" android:pathData="M$RULE_X,${RULE_Y}h${RULE_W}v${RULE_H}h-${RULE_W}z"/>
EOF
}

# Adaptive foreground / monochrome: 108 dp canvas, the mark stays inside the
# 66 dp safe circle (scale 2.2: 40 × 46 dp, centred at 54).
MS=2.2
MTX=$(calc "54 - $CX * $MS")
MTY=$(calc "54 - (3 + $RULE_Y + $RULE_H) / 2 * $MS")
adaptive_layer() {
  cat > "$RES/drawable/$1.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/tool/generate_icons.sh. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="$MTX" android:translateY="$MTY"
        android:scaleX="$MS" android:scaleY="$MS">
$(mark_paths "$2" "$3")
    </group>
</vector>
EOF
}
adaptive_layer ic_launcher_foreground "#FF${PAPER#\#}" "#FF${RULE#\#}"
adaptive_layer ic_launcher_monochrome "#FFFFFFFF" "#FFFFFFFF"   # alpha only

# Splash icon (Android 12+ SplashScreen + legacy launch_background): 288 dp
# canvas, a 144 dp Ink tile (radius 24, the desktop tile's proportion) that
# fits the 192 dp mask circle, on the Board window background.
SS=3.9
STX=$(calc "72 - $CX * $SS")
STY=$(calc "72 - (3 + $RULE_Y + $RULE_H) / 2 * $SS")
cat > "$RES/drawable/splash_icon.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/tool/generate_icons.sh. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="288dp" android:height="288dp"
    android:viewportWidth="288" android:viewportHeight="288">
    <group android:translateX="72" android:translateY="72">
        <path android:fillColor="#FF${INK#\#}"
            android:pathData="M24,0h96a24,24 0,0 1,24 24v96a24,24 0,0 1,-24 24h-96a24,24 0,0 1,-24 -24v-96a24,24 0,0 1,24 -24z"/>
        <group android:translateX="$STX" android:translateY="$STY"
            android:scaleX="$SS" android:scaleY="$SS">
$(mark_paths "#FF${PAPER#\#}" "#FF${RULE#\#}")
        </group>
    </group>
</vector>
EOF

# ---- Shrink PNGs -------------------------------------------------------------
find "$WEB" "$LX" "$RES" -name '*.png' -print0 | xargs -0 oxipng -q -o 4 --strip safe

echo "Icons regenerated."
