#!/usr/bin/env bash
# Regenerates every platform icon of Len from one design.
#
#   app/tool/generate_icons.sh        (from anywhere; needs Nix or resvg+magick+oxipng)
#
# Source of truth:
#   tool/branding/glyph.path   the mark: Material Symbols "gesture" (rounded),
#                              24×24 units, the same glyph as the in-app logo
#                              (`Icons.gesture_rounded` in the library sidebar).
#                              Apache-2.0 (Google Material Icons).
#   this script                colours and geometry of every variant.
#
# Outputs (all committed):
#   tool/branding/*.svg                         design variants (also previews)
#   web/icons/*, web/favicon.png                PWA / browser icons
#   android/app/src/main/res/{drawable,mipmap-*}/   adaptive (vector) + legacy PNGs
#   windows/runner/resources/app_icon.ico
#   linux/packaging/icons/                      hicolor PNGs + scalable SVG
set -euo pipefail

if ! command -v resvg >/dev/null || ! command -v magick >/dev/null || ! command -v oxipng >/dev/null; then
  exec nix shell nixpkgs#resvg nixpkgs#imagemagick nixpkgs#oxipng -c bash "$0" "$@"
fi

APP="$(cd "$(dirname "$0")/.." && pwd)"
BR="$APP/tool/branding"
GLYPH="$(tr -d '\n' < "$BR/glyph.path")"

# Brand colours: the tile gradient mirrors the sidebar logo
# (lerp(primary, white, .15) → primary of the ink-blue seed #3B5BDB).
C1="#5470E3"
C2="#2E4BC6"
SHADOW="#16246E"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# ---- SVG variants ----------------------------------------------------------
# $1 file, $2 tile element(s), $3 glyph scale, $4 glyph translate, $5 shadow (0/1)
svg() {
  local file=$1 tile=$2 s=$3 t=$4 shadow=$5 filter=""
  [[ $shadow == 1 ]] && filter=' filter="url(#s)"'
  cat > "$file" <<EOF
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <!-- Len app icon. Generated by app/tool/generate_icons.sh — edit there. -->
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="$C1"/>
      <stop offset="1" stop-color="$C2"/>
    </linearGradient>
    <linearGradient id="h" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity=".16"/>
      <stop offset=".55" stop-color="#FFFFFF" stop-opacity="0"/>
    </linearGradient>
    <filter id="s" x="-20%" y="-20%" width="140%" height="140%">
      <feDropShadow dx="0" dy="6" stdDeviation="9" flood-color="$SHADOW" flood-opacity=".35"/>
    </filter>
  </defs>
  $tile
  <path transform="translate($t $t) scale($s)" fill="#FFFFFF"$filter d="$GLYPH"/>
</svg>
EOF
}

rounded='<rect x="24" y="24" width="464" height="464" rx="104" fill="url(#g)"/>
  <rect x="24" y="24" width="464" height="464" rx="104" fill="url(#h)"/>'
square='<rect width="512" height="512" fill="url(#g)"/>
  <rect width="512" height="512" fill="url(#h)"/>'
circle='<circle cx="256" cy="256" r="236" fill="url(#g)"/>
  <circle cx="256" cy="256" r="236" fill="url(#h)"/>'

# Glyph spans 3..21 of its 24-unit box (centre 12): translate = 256 - 12·s.
svg "$BR/len.svg"          "$rounded" 14.5 82  1   # desktop, web "any", legacy launcher
svg "$BR/len-maskable.svg" "$square"  12   112 1   # full bleed, glyph inside 80 % safe zone
svg "$BR/len-round.svg"    "$circle"  13   100 1   # Android legacy round launcher
svg "$BR/len-touch.svg"    "$square"  14   88  1   # iOS home screen (iOS rounds it)

render() { resvg -w "$2" -h "$2" "$1" "$3"; }

# ---- Web -------------------------------------------------------------------
WEB="$APP/web"
cp "$BR/len.svg" "$WEB/icons/len.svg"
cp "$BR/len-maskable.svg" "$WEB/icons/len-maskable.svg"
render "$BR/len.svg" 192 "$WEB/icons/Icon-192.png"
render "$BR/len.svg" 512 "$WEB/icons/Icon-512.png"
render "$BR/len-maskable.svg" 192 "$WEB/icons/Icon-maskable-192.png"
render "$BR/len-maskable.svg" 512 "$WEB/icons/Icon-maskable-512.png"
render "$BR/len-touch.svg" 180 "$WEB/icons/apple-touch-icon.png"
render "$BR/len.svg" 32 "$WEB/favicon.png"

# ---- Windows (.ico with the sizes Explorer / taskbar use) ------------------
ico=()
for s in 16 20 24 32 40 48 64 96 128 256; do
  render "$BR/len.svg" $s "$TMP/ico-$s.png"
  ico+=("$TMP/ico-$s.png")
done
magick "${ico[@]}" "$APP/windows/runner/resources/app_icon.ico"

# ---- Linux (hicolor theme, installed into the bundle by linux/CMakeLists.txt) ----
LX="$APP/linux/packaging/icons"
rm -rf "$LX"
for s in 32 48 64 128 256 512; do
  mkdir -p "$LX/${s}x${s}/apps"
  render "$BR/len.svg" $s "$LX/${s}x${s}/apps/dev.len.len.png"
done
mkdir -p "$LX/scalable/apps"
cp "$BR/len.svg" "$LX/scalable/apps/dev.len.len.svg"

# ---- Android ---------------------------------------------------------------
RES="$APP/android/app/src/main/res"
declare -A dens=([mdpi]=48 [hdpi]=72 [xhdpi]=96 [xxhdpi]=144 [xxxhdpi]=192)
for d in "${!dens[@]}"; do
  mkdir -p "$RES/mipmap-$d"
  render "$BR/len.svg" "${dens[$d]}" "$RES/mipmap-$d/ic_launcher.png"
  render "$BR/len-round.svg" "${dens[$d]}" "$RES/mipmap-$d/ic_launcher_round.png"
done

mkdir -p "$RES/mipmap-anydpi-v26" "$RES/drawable"
for name in ic_launcher ic_launcher_round; do
  cat > "$RES/mipmap-anydpi-v26/$name.xml" <<'EOF'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/tool/generate_icons.sh. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <!-- Android 13+ themed icons: the glyph's alpha, tinted by the system. -->
    <monochrome android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
EOF
done

# Gradient fill shared by the vector drawables ($1 = size in viewport units).
gradient() {
  cat <<EOF
            <aapt:attr name="android:fillColor">
                <gradient android:type="linear" android:startX="0" android:startY="0"
                    android:endX="$1" android:endY="$1">
                    <item android:offset="0" android:color="#FF${C1#\#}"/>
                    <item android:offset="1" android:color="#FF${C2#\#}"/>
                </gradient>
            </aapt:attr>
EOF
}

cat > "$RES/drawable/ic_launcher_background.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/tool/generate_icons.sh. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
$(gradient 108)
    </path>
</vector>
EOF

# Adaptive foreground: 108 dp canvas, the glyph stays inside the 66 dp safe
# circle (scale 2.2 → 40 dp, centred at 54).
cat > "$RES/drawable/ic_launcher_foreground.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/tool/generate_icons.sh. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="27.6" android:translateY="27.6"
        android:scaleX="2.2" android:scaleY="2.2">
        <path android:fillColor="#FFFFFFFF" android:pathData="$GLYPH"/>
    </group>
</vector>
EOF

# Splash icon (Android 12+ SplashScreen + legacy launch_background):
# 288 dp canvas, a 144 dp rounded tile that fits the 192 dp mask circle.
cat > "$RES/drawable/splash_icon.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/tool/generate_icons.sh. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="288dp" android:height="288dp"
    android:viewportWidth="288" android:viewportHeight="288">
    <group android:translateX="72" android:translateY="72">
        <path android:pathData="M32.3,0h79.4a32.3,32.3 0,0 1,32.3 32.3v79.4a32.3,32.3 0,0 1,-32.3 32.3h-79.4a32.3,32.3 0,0 1,-32.3 -32.3v-79.4a32.3,32.3 0,0 1,32.3 -32.3z">
$(gradient 144)
        </path>
        <group android:translateX="18" android:translateY="18"
            android:scaleX="4.5" android:scaleY="4.5">
            <path android:fillColor="#FFFFFFFF" android:pathData="$GLYPH"/>
        </group>
    </group>
</vector>
EOF

# ---- Shrink PNGs -------------------------------------------------------------
find "$WEB" "$LX" "$RES" -name '*.png' -print0 | xargs -0 oxipng -q -o 4 --strip safe

echo "Icons regenerated."
